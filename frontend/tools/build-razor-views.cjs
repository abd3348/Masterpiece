// Preserve the existing frontend while moving every screen into real Razor views.
// Re-run after changing the HTML design sources; application code stays in JS.
const fs=require('node:fs'),path=require('node:path');
const groups=['public','auth','tenant','landlord','admin'];
const catalog=[];
for(const group of groups) {
    const dir='backend/Views/'+group[0].toUpperCase()+group.slice(1);
    fs.mkdirSync(dir,{recursive:true});
    for(const file of fs.readdirSync('html/'+group).filter(n=>n.endsWith('.html'))) {
        const source=fs.readFileSync('html/'+group+'/'+file,'utf8').replace(/\r\n/g,'\n').replaceAll('../../backend/wwwroot/','../../').replace(/<\/(\w+)\s+>/g,'</$1>');
        const head=source.match(/<head\s*>([\s\S]*?)<\/head\s*>/i);
        const body=source.match(/<body\b([^>]*)>([\s\S]*?)<\/body\s*>/i);
        if(!head||!body)throw Error('Cannot parse '+group+'/'+file);
        const title=head[1].match(/<title\s*>([\s\S]*?)<\/title>/i)?.[1].trim()||'Campus Mate';
        let headContent=head[1].replace(/<title\s*>[\s\S]*?<\/title>/i,'').replace(/<script[^>]*src="https:\/\/mcp\.figma\.com[^>]*><\/script>/gi,'');
        const attrs=Object.fromEntries([...body[1].matchAll(/([\w-]+)="([^"]*)"/g)].map(m=>[m[1],m[2]]));
        const name=file.slice(0,-5),view=group[0].toUpperCase()+group.slice(1)+'/'+name;
        catalog.push({group,name,view,title,attrs});
        const razor='@model CampusMate.ViewModels.ScreenViewModel\n@{ Layout = "_ScreenLayout"; }\n@section Head {\n'+headContent.trim().replaceAll('@','@@')+'\n}\n'+body[2].trim().replaceAll('@','@@')+'\n';
        fs.writeFileSync(dir+'/'+name+'.cshtml',razor);
    }
}
const literal=s=>JSON.stringify(s||'');
let cs='// Generated by tools/build-razor-views.cjs\nnamespace CampusMate.ViewModels;\npublic sealed record ScreenViewModel(string View, string Section, string Screen, string Title, string? Page, string? Tab, string? BodyClass);\npublic static class ScreenCatalog {\n    public static readonly IReadOnlyDictionary<string,ScreenViewModel> Screens = new Dictionary<string,ScreenViewModel>(StringComparer.OrdinalIgnoreCase) {\n';
for(const c of catalog)cs+=`        [${literal(c.group+'/'+c.name)}] = new(${literal(c.view)}, ${literal(c.group)}, ${literal(c.name)}, ${literal(c.title)}, ${literal(c.attrs['data-page'])}, ${literal(c.attrs['data-tab'])}, ${literal(c.attrs.class)}),\n`;
cs+='    };\n}\n';fs.mkdirSync('backend/ViewModels',{recursive:true});fs.writeFileSync('backend/ViewModels/ScreenViewModel.cs',cs);
let shell=fs.readFileSync('index.html','utf8').replaceAll('backend/wwwroot/','').replace(/\s*<script src="js\/(?:pages|seed|demo-showcase)\.js"><\/script>/g,'').replaceAll('@','@@');
fs.writeFileSync('backend/Views/Home/Index.cshtml','@{ Layout = null; }\n'+shell);
console.log(`Generated ${catalog.length} Razor screens and the MVC application shell.`);
